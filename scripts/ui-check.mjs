import { chromium } from 'playwright';
import { mkdirSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const base = process.env.AGENTGUARD_URL || 'https://demo.guardcmd.ai';
mkdirSync('evidence',{recursive:true});
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto(base,{waitUntil:'networkidle'});
await page.getByRole('heading',{name:'Move in parallel. Merge with confidence.'}).waitFor();
await page.screenshot({path:'evidence/dashboard-desktop.png',fullPage:true});
await page.getByRole('button',{name:'Workspace access',exact:true}).click();
assert.equal(await page.getByRole('dialog').isVisible(),true);
await page.getByRole('button',{name:'Close',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'evidence/dashboard-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false,'Mobile horizontal overflow');
assert.deepEqual(errors,[]);
writeFileSync('evidence/ui-check.json',JSON.stringify({base,checkedAt:new Date().toISOString(),desktop:[1440,1100],mobile:[390,844],pageErrors:errors,dialog:true,mobileOverflow:false},null,2));
await browser.close();
console.log('Desktop/mobile UI checks passed; screenshots saved.');
